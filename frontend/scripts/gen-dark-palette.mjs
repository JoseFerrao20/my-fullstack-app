// Generates src/app/dark.css: dark mode by inverting Tailwind's color scales under `.dark`.
//
// Every utility (bg-white, text-slate-900, bg-red-50 ...) reads a CSS variable, so swapping
// 50<->950, 100<->900, ... turns light surfaces dark and dark text light across the whole app,
// without dark: variants in every component. Run `npm run gen:dark` after adding a new palette.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const PALETTES = ["slate", "indigo", "red", "emerald", "amber", "blue", "sky"];
const SHADES = ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"];

const require = createRequire(import.meta.url);
const themeCss = readFileSync(require.resolve("tailwindcss/theme.css"), "utf8");
const value = (name) => {
  const match = themeCss.match(new RegExp(`--color-${name}:\\s*([^;]+);`));
  if (!match) throw new Error(`Tailwind color --color-${name} not found`);
  return match[1].trim();
};

const lines = [];
for (const palette of PALETTES) {
  SHADES.forEach((shade, i) => {
    const mirrored = SHADES[SHADES.length - 1 - i];
    lines.push(`  --color-${palette}-${shade}: ${value(`${palette}-${mirrored}`)};`);
  });
}

const css = `/* Generated by scripts/gen-dark-palette.mjs (npm run gen:dark). Do not edit by hand. */
/* Not inside a @layer, so these win over Tailwind's own theme variables. */
.dark {
  color-scheme: dark;
  /* Cards and inputs ("white") become the raised dark surface; the page (slate-50) goes darkest. */
  --color-white: ${value("slate-900")};
  --color-black: ${value("white")};
${lines.join("\n")}
}

/* Overlays should still darken what's behind them. */
.dark dialog::backdrop {
  background-color: rgb(0 0 0 / 0.6);
}
`;

writeFileSync(new URL("../src/app/dark.css", import.meta.url), css);
console.log("wrote src/app/dark.css");
